const fs = require('node:fs');
const assert = require('node:assert/strict');
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');
(async () => {
 const db = new PGlite();
 await db.exec(`
 create role authenticated; create role anon; create schema auth;
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 create function public.is_admin() returns boolean language sql stable as $$ select false $$;
 create function public.is_competition_member(uuid) returns boolean language sql stable as $$ select auth.uid() is not null $$;
 create function public.star_man_lock_at_for_gameweek(uuid,bigint) returns timestamptz language sql stable as $$ select now()-interval '1 day' $$;
 create table gameweeks(id bigint,season_id uuid);
 create table players(id uuid,team_id uuid);
 create table fixtures(id bigint,season_id uuid,gameweek_id bigint,home_team_id uuid,away_team_id uuid,kickoff_at timestamptz,status text);
 create table player_team_assignments(player_id uuid,season_id uuid,team_id uuid,starts_gameweek_id bigint,ends_gameweek_id bigint);
 create table card_definitions(id text,effect_key text);
 create table active_card_effects(id uuid,card_id text,competition_id uuid,season_id uuid,gameweek_id bigint,start_gameweek_id bigint,end_gameweek_id bigint,played_by_user_id uuid,target_user_id uuid,status text,fixture_id bigint);
 create table star_man_picks(competition_id uuid,season_id uuid,gameweek_id bigint,user_id uuid,player_id uuid,pick_slot text,source_card_effect_id uuid);
 `);
 const id = n => `00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
 const [comp,season,user,other,player,pastPlayer,team,pastTeam,effect] = Array.from({length:9},(_,i)=>id(i+1));
 await db.exec(`insert into gameweeks values (4,'${season}');
 insert into players values ('${player}','${team}'),('${pastPlayer}','${pastTeam}');
 insert into fixtures values (1,'${season}',4,'${team}',null,now()+interval '1 hour','scheduled'),(2,'${season}',4,'${pastTeam}',null,now()-interval '1 hour','final');
 insert into card_definitions values ('power_late_scout','power_late_scout');
 insert into active_card_effects values ('${effect}','power_late_scout','${comp}','${season}',4,4,4,'${user}',null,'active',null);`);
 await db.exec(fs.readFileSync('supabase/late-scout-save-and-privacy-2026-09-13.sql','utf8'));
 await db.exec(`alter table star_man_picks enable row level security;
 create policy existing_read on star_man_picks for select to authenticated using (true);
 create policy existing_insert on star_man_picks for insert to authenticated with check (can_submit_star_man_pick(competition_id,season_id,gameweek_id,user_id,player_id,pick_slot,source_card_effect_id));
 create policy existing_update on star_man_picks for update to authenticated using (user_id=auth.uid()) with check (can_submit_star_man_pick(competition_id,season_id,gameweek_id,user_id,player_id,pick_slot,source_card_effect_id));
 grant usage on schema public,auth to authenticated; grant select on all tables in schema public to authenticated; grant insert,update on star_man_picks to authenticated;
 set role authenticated; select set_config('request.jwt.claim.sub','${user}',false);`);
 const allowed = async (p=player,src=effect,gw=4,u=user) => (await db.query(`select can_submit_star_man_pick('${comp}','${season}',${gw},'${u}','${p}','primary',${src ? `'${src}'` : 'null'}) as ok`)).rows[0].ok;
 assert.equal(await allowed(),true,'no original pick + future fixture allowed');
 assert.equal(await allowed(pastPlayer),false,'started replacement blocked');
 assert.equal(await allowed(player,null),false,'no card blocked');
 assert.equal(await allowed(player,effect,5),false,'wrong week blocked');
 assert.equal(await allowed(player,effect,4,other),false,'another user blocked');
 await db.exec(`insert into star_man_picks values ('${comp}','${season}',4,'${user}','${player}','primary','${effect}');`);
 assert.equal((await db.query('select * from star_man_picks')).rows.length,1,'owner sees own pick');
 await db.exec(`select set_config('request.jwt.claim.sub','${other}',false);`);
 assert.equal((await db.query('select * from star_man_picks')).rows.length,0,'opponent cannot see changeable pick');
 await db.exec(`reset role; update fixtures set kickoff_at=now()-interval '1 second' where id=1; set role authenticated;`);
 assert.equal((await db.query('select * from star_man_picks')).rows.length,1,'opponent sees pick after kickoff');
 await db.exec(`select set_config('request.jwt.claim.sub','${user}',false);`);
 assert.equal(await allowed(),false,'selected kickoff locks saving');
 await db.exec('reset role');
 await db.exec(fs.readFileSync('supabase/late-scout-save-and-privacy-2026-09-13.sql','utf8'));
 console.log('PASS: save eligibility, ownership, missing/invalid source, gameweek, kickoff privacy, and migration idempotency');
 await db.close();
})().catch(e => { console.error(e); process.exitCode=1; });
